//! 主窗口启动尺寸适配。
//!
//! 窗口默认按 tauri.conf.json 的 1440×900（逻辑像素）打开；但在高缩放比的
//! 小屏上（典型如 1920×1200 配 Windows 150% 缩放，可用宽度被压缩到 1280
//! 逻辑像素），默认窗口比屏幕还宽，右缘连同标题栏按钮一起溢出屏幕外，
//! 用户既看不到也拖不回来。启动时按当前屏幕的可用区域（已扣除任务栏）
//! 收缩窗口，保证整个窗口完整落在屏幕内；大屏不受影响。

/// 计算主窗口的启动尺寸（逻辑像素）：期望尺寸放得下就原样使用（只缩不放），
/// 放不下则收缩到屏幕可用区域。
pub fn fit_startup_size(desired: (f64, f64), available: (f64, f64)) -> (f64, f64) {
    (
        desired.0.min(available.0).max(1.0),
        desired.1.min(available.1).max(1.0),
    )
}

#[cfg(test)]
mod tests {
    use super::fit_startup_size;

    #[test]
    fn 常规大屏保持默认窗口尺寸() {
        // 1920×1080@100%：默认 1440×900 放得下，不动。
        assert_eq!(
            fit_startup_size((1440.0, 900.0), (1920.0, 1040.0)),
            (1440.0, 900.0)
        );
    }

    #[test]
    fn 高缩放小屏收缩到屏幕可用区域() {
        // 用户反馈场景：1920×1200@150%，可用区域约 1280×752 逻辑像素。
        assert_eq!(
            fit_startup_size((1440.0, 900.0), (1280.0, 752.0)),
            (1280.0, 752.0)
        );
    }

    #[test]
    fn 只缺高度时按高度收缩() {
        // 1366×768@125% 之类的紧凑屏：宽度勉强够、高度不够。
        assert_eq!(
            fit_startup_size((1440.0, 900.0), (1366.0, 640.0)),
            (1366.0, 640.0)
        );
    }

    #[test]
    fn 超大屏不放大窗口() {
        assert_eq!(
            fit_startup_size((1440.0, 900.0), (3840.0, 2160.0)),
            (1440.0, 900.0)
        );
    }
}
